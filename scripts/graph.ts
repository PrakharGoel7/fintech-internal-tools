/**
 * Module dependency graph: blocks (versioned) → the shared files they're built from → apps that use them.
 *   npm run graph                 write module-graph.json (apps record the block versions they were verified against)
 *   npm run graph -- --check      fail if module-graph.json is stale
 *   npm run graph -- --diff <ref> list changed blocks + affected apps vs <ref>, and fail if a changed block's
 *                                 version wasn't bumped enough (config schema break → major, new options → minor, else patch)
 */
import fs from "node:fs";
import { execSync } from "node:child_process";
import { zodToJsonSchema } from "zod-to-json-schema";
import { manifests } from "@/blocks/manifests";
import { apps } from "@/apps/registry";
import { importGraph, closure, bumpOf, atLeast, schemaChange, type Bump } from "./graph-lib";

const FILE = "module-graph.json";

function build() {
  const g = importGraph();
  const blocks = Object.fromEntries(Object.values(manifests).map((m) => {
    const own = [...g.keys()].filter((f) => f.startsWith(`src/blocks/${m.name}/`));
    const reach = closure(g, own, ["src/blocks/", "src/platform/", "src/connectors/"]);
    return [m.name, { version: m.version, files: reach.filter((f) => f.startsWith("src/blocks/")), platform: reach.filter((f) => !f.startsWith("src/blocks/")) }];
  }));
  const appNodes = Object.fromEntries(apps.map((a) => {
    const used = [...new Set(a.pages.flatMap((p) => p.blocks.map((b) => b.type)))].sort();
    const fromBlocks = a.pages.flatMap((p) => p.blocks.map((b) => (b.config as { source?: unknown }).source)).filter((s): s is string => typeof s === "string");
    const sources = [...new Set([...Object.values(a.actions).map((x) => x.source), ...fromBlocks])].sort();
    return [a.slug, { blocks: Object.fromEntries(used.map((b) => [b, manifests[b].version])), sources }];
  }));
  return { $comment: "GENERATED by `npm run graph` — do not edit by hand.", blocks, apps: appNodes };
}

function diff(ref: string, graph: ReturnType<typeof build>) {
  const sh = (c: string) => execSync(c, { encoding: "utf8" }).trim();
  const base = sh(`git merge-base ${ref} HEAD`);
  const changed = sh(`git diff --name-only ${base}`).split("\n").filter(Boolean);
  const baseCatalog = JSON.parse(sh(`git show ${base}:catalog.json`)) as { blocks: { name: string; version: string; configSchema: object }[] };
  const usedBy = (block: string) => Object.entries(graph.apps).filter(([, a]) => block in a.blocks).map(([s]) => s);
  const errors: string[] = [];
  const rows: string[] = [];
  const affected = new Set<string>();

  for (const [name, node] of Object.entries(graph.blocks)) {
    const files = node.files.filter((f) => changed.includes(f));
    if (!files.length) continue;
    const apps = usedBy(name);
    apps.forEach((a) => affected.add(a));
    const prev = baseCatalog.blocks.find((b) => b.name === name);
    if (!prev) { rows.push(`| ${name} | new → ${node.version} | — | ✅ | ${apps.join(", ") || "—"} |`); continue; }
    const schema = zodToJsonSchema(manifests[name].configSchema, { target: "jsonSchema7", $refStrategy: "none" });
    const s = schemaChange(prev.configSchema, schema);
    const need: Bump = s === "none" ? "patch" : s;
    const have = bumpOf(prev.version, node.version);
    const ok = have !== null && atLeast(have, need);
    rows.push(`| ${name} | ${prev.version} → ${node.version} | ${need} | ${ok ? "✅" : "❌"} | ${apps.join(", ") || "—"} |`);
    if (!ok) errors.push(`${name}: changed (${files.join(", ")}) with a ${need}-level change; bump version from ${prev.version} (now ${node.version}) in src/blocks/${name}/manifest.ts. Used by: ${apps.join(", ") || "no apps"}`);
  }
  const platformFiles = changed.filter((f) => f.startsWith("src/platform/") || f.startsWith("src/connectors/"));
  if (platformFiles.length) Object.keys(graph.apps).forEach((a) => affected.add(a));
  for (const f of changed) { const m = f.match(/^src\/apps\/([^/]+)\//); if (m && m[1] in graph.apps) affected.add(m[1]); }

  const report = [
    "### Module changes",
    rows.length ? "| Block | Version | Change needs | OK | Used by |\n|---|---|---|---|---|\n" + rows.join("\n") : "No block changed.",
    platformFiles.length ? `\nPlatform/connector files changed (${platformFiles.join(", ")}): every app is affected.` : "",
    `\n**Affected apps** (their scenarios + smoke must pass): ${[...affected].sort().join(", ") || "none"}`,
  ].join("\n");
  console.log(report);
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, report + "\n");
  if (errors.length) { console.error("\n" + errors.join("\n")); process.exit(1); }
}

const graph = build();
const out = JSON.stringify(graph, null, 2) + "\n";
const i = process.argv.indexOf("--diff");
if (i > -1) diff(process.argv[i + 1] ?? "origin/main", graph);
else if (process.argv.includes("--check")) {
  if ((fs.existsSync(FILE) ? fs.readFileSync(FILE, "utf8") : "") !== out) { console.error(`${FILE} is stale — run \`npm run graph\``); process.exit(1); }
  console.log(`${FILE} up to date`);
} else {
  fs.writeFileSync(FILE, out);
  console.log(`${FILE}: ${Object.keys(graph.blocks).length} blocks, ${Object.keys(graph.apps).length} apps`);
}
