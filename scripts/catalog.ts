/** Generates catalog.json — the machine-readable module catalog Devin reads before composing an app. */
import fs from "node:fs";
import { zodToJsonSchema } from "zod-to-json-schema";
import { manifests } from "@/blocks/manifests";
import { sources } from "@/connectors";
import { externalConnectors } from "@/connectors/external";
import { apps } from "@/apps/registry";

const catalog = {
  $comment: "GENERATED by `npm run catalog` — do not edit by hand.",
  blocks: Object.values(manifests).map(({ configSchema, ...m }) => ({
    ...m,
    usedBy: apps.filter((a) => a.pages.some((p) => p.blocks.some((b) => b.type === m.name))).map((a) => a.slug),
    configSchema: zodToJsonSchema(configSchema, { target: "jsonSchema7", $refStrategy: "none" }),
  })),
  connectors: {
    tables: Object.values(sources).map((s) => ({ name: s.def.name, pk: s.def.pk, piiFields: s.def.piiFields, fields: s.def.fields })),
    external: Object.fromEntries(Object.entries(externalConnectors).map(([k, ops]) => [k, Object.keys(ops)])),
  },
  apps: apps.map((a) => ({ slug: a.slug, name: a.name, permissions: Object.keys(a.permissions), actions: Object.keys(a.actions), blocks: [...new Set(a.pages.flatMap((p) => p.blocks.map((b) => b.type)))] })),
};

const out = JSON.stringify(catalog, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const cur = fs.existsSync("catalog.json") ? fs.readFileSync("catalog.json", "utf8") : "";
  if (cur !== out) { console.error("catalog.json is stale — run `npm run catalog`"); process.exit(1); }
  console.log("catalog.json up to date");
} else {
  fs.writeFileSync("catalog.json", out);
  console.log(`catalog.json: ${catalog.blocks.length} blocks, ${catalog.apps.length} apps`);
}
